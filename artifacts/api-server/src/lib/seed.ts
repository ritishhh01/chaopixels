export async function seedIfEmpty(): Promise<void> {
  try {
    const result = await db.select({ total: count() }).from(wallpapersTable);
    const totalCount = result[0]?.total ?? 0;

    if (totalCount >= SEED_VERSION) {
      logger.info({ totalCount }, "Database already seeded, skipping");
      return;
    }

    if (totalCount > 0) {
      logger.info({ totalCount }, "Re-seeding database with updated wallpaper collection");
      await db.delete(wallpapersTable);
    } else {
      logger.info("Database is empty, seeding wallpapers...");
    }

    await db.insert(wallpapersTable).values(SEED_WALLPAPERS);
    logger.info({ count: SEED_WALLPAPERS.length }, "Seeded wallpapers successfully");
  } catch (err) {
    logger.error({ err }, "Failed to seed wallpapers");
  }
}
